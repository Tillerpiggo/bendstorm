import type { ElementId } from './types';

/** The basic ranged attack. Speeds in units/s, times in seconds, angle in degrees above horizontal. */
export interface BoltSpec {
  startup: number;
  recovery: number;
  speed: number;
  vy0: number;
  gravity: number;
  /** Vertical steering toward the opponent, in units/s². 0 flies straight. */
  homing: number;
  radius: number;
  life: number;
  dmg: number;
  base: number;
  growth: number;
  angle: number;
  /** When two bolts collide the lower priority one dies; equal priority kills both. */
  priority: number;
}

export interface ElementDef {
  id: ElementId;
  name: string;
  title: string;
  tagline: string;
  /** Presentation colours, CSS hex. `particles` runs hot core → cool edge. */
  color: string;
  glow: string;
  robe: string;
  trim: string;
  skin: string;
  hair: string;
  particles: [string, string, string];
  runSpeed: number;
  jumpVel: number;
  airJumps: number;
  /** Knockback taken is divided by this. */
  weight: number;
  recoverVel: number;
  bolt: BoltSpec;
  specialCd: number;
  /** Shots in a full burst, and seconds to win one back once you stop firing. */
  ammo: number;
  reload: number;
  /** Bot hints: how close to be before using the special, and preferred spacing. */
  specialRange: number;
  botRange: number;
  moves: { bolt: string; special: string; specialHint: string; side: string; sideHint: string; down: string; downHint: string; recover: string; ult: string; ultHint: string };
  /** 1-5, for the select screen only. */
  stats: { power: number; speed: number; weight: number; reach: number };
}

